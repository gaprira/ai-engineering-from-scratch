import random

print("=== НАЧАЛО ОБУЧЕНИЯ НЕЙРОНА ===\n")

# 1. ИНИЦИАЛИЗАЦИЯ (Бросаем кости)
# Нейрон ничего не знает, поэтому начинаем со случайных чисел
weight = random.uniform(-1, 1)  # Случайный вес
bias = random.uniform(-1, 1)  # Случайное смещение
learning_rate = 0.1  # Скорость обучения (насколько сильно крутим ручки)

print(f"Старт: Вес = {weight:.4f}, Смещение = {bias:.4f} (Полный мусор)\n")

# 2. ДАННЫЕ ДЛЯ ТРЕНИРОВКИ (Учебник с ответами)
# Мы знаем правило (2 * вход + 1), но нейрон его не видит.
# Он видит только пары: (входное_число, правильный_ответ)
training_data = [
    (1, 3),  # Вход 1 -> Ответ 3
    (2, 5),  # Вход 2 -> Ответ 5
    (3, 7),  # Вход 3 -> Ответ 7
    (4, 9),  # Вход 4 -> Ответ 9
]

# 3. ПРОЦЕСС ОБУЧЕНИЯ (Тысячи попыток, у нас будет 20 циклов для примера)
epochs = 100  # Эпоха = один полный проход по всем примерам в учебнике

for epoch in range(epochs):
    total_error = 0  # Суммарная ошибка за этот цикл

    for input_value, true_answer in training_data:

        # ШАГ А: Прямой проход (Нейрон делает предсказание)
        # Формула нейрона: предсказание = (вход * вес) + смещение
        prediction = (input_value * weight) + bias

        # ШАГ Б: Вычисление ошибки (Насколько сильно промахнулись?)
        # Ошибка = предсказание минус правда
        error = prediction - true_answer
        total_error += abs(error)  # Накапливаем общую ошибку

        # ШАГ В: Обратный проход (Подкрутка весов!)
        # Это самая важная часть машинного обучения (Градиентный спуск).

        # Как подкрутить ВЕС?
        # Если входное число было большим, и мы ошиблись, значит вес виноват сильнее.
        # Поэтому мы умножаем ошибку на входное число.
        weight_correction = error * input_value
        weight = weight - (learning_rate * weight_correction)

        # Как подкрутить СМЕЩЕНИЕ?
        # Смещение не зависит от входа, оно виновато просто на величину ошибки.
        bias_correction = error
        bias = bias - (learning_rate * bias_correction)

    # Печатаем прогресс каждые 5 эпох
    if epoch % 5 == 0:
        avg_error = total_error / len(training_data)
        print(
            f"Эпоха {epoch:2d} | Средняя ошибка: {avg_error:.4f} | Вес: {weight:.4f} | Смещение: {bias:.4f}"
        )

# 4. ФИНАЛЬНАЯ ПРОВЕРКА
print("\n=== КОНЕЦ ОБУЧЕНИЯ ===")
print(f"Итоговый Вес нейрона:      {weight:.2f} (Загадано было: 2)")
print(f"Итоговое Смещение нейрона: {bias:.2f} (Загадано было: 1)")

print("\nПроверяем, как нейрон работает на новых данных (которых не было в учебнике):")
test_input = 10
test_prediction = (test_input * weight) + bias
print(
    f"Если на вход дать 10, нейрон predict: {test_prediction:.2f} (Правильный ответ: 21)"
)
